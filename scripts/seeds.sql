    ('normal', 'Антиоксидантная защита', 'Дневной уход с витамином С или зеленым чаем защищает от преждевременного старения.'),

    -- Комбинированная кожа
    ('combination', 'Тонизирование сыворотками-эссенциями', 'Использование водянистых текстур дает питание без закупорки пор в Т-зоне.'),
    ('combination', 'Обновление и текстура', 'Протокол со спикулами и бакучиолом для разглаживания рельефа и сужения пор.'),

    -- Жирная кожа
