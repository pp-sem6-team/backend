    v.skin_type::skin_type,
    v.title,
    v.description
FROM (
    VALUES
    -- Сухая кожа
    ('dry', 'Слоение текстур', 'Последовательное нанесение тонера, сыворотки и крема создает «замок» для влаги.'),
